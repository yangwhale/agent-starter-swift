import SwiftUI

/// **这一页现在需要画吗。**
///
/// Chris 2026-09-22 00:42：
/// 「只有在前台的那个房间才需要渲染，那没有被放在前台的房间，
///  一律都不要做任何的动画，只有音频播放一件事情。
///  那看不见的东西瞎做你啥呢？省电为主。
///  在锁屏的时候，所有的刷新都不要，就光播放音频就行了。」
///
/// ## 为什么必须显式做这件事
///
/// SwiftUI **不会**因为一个视图被别的页遮住就停掉它的定时器。
/// `TabView` 的分页样式为了滑动跟手，**相邻页是同时活着的**；
/// 而 `Task { while true { ... sleep } }` 这种泵更是跟视图可见性完全无关 ——
/// 它只认「有没有人 cancel」。
///
/// ⇒ 所以「看不见就不画」不是默认行为，**是要一处处接线的**。
/// 这个环境值就是那根线：`CCRootView` 在每一页上算一次，
/// 叶子视图读它决定要不要开定时器。
///
/// ## 三个条件，缺一个都要停
///
/// 1. **是当前页** —— 五个房间挂着，只有一个在屏幕上
/// 2. **场景在前台** —— 锁屏、切后台、进 app 切换器
/// 3. （叶子自己的条件，比如「有没有在说话」）
///
/// ## ⚠️ 它只关「画」，不关「听」
///
/// 音频播放**不受它影响** —— 后台房间照样收音频、照样出声，
/// `Info.plist` 里的 `UIBackgroundModes: audio` 就是为这个开的。
/// 停掉的只有：30fps 的柱子泵、`TimelineView` 的周期重算、
/// 背景那层永不停的模糊动画、以及播放进度的轮询。
///
/// **「省电」在这里的准确含义是「不画看不见的东西」，不是「少干活」。**
extension EnvironmentValues {
    @Entry var ccRendering: Bool = true
}

extension View {
    /// 给这棵子树声明「要不要画」。
    func ccRendering(_ on: Bool) -> some View {
        environment(\.ccRendering, on)
    }
}
